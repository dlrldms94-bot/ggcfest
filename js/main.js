function rnd(seed) {
  const x = Math.sin(seed * 9999.123) * 43758.5453;
  return x - Math.floor(x);
}

function paintStarfield(root) {
  const w = 1800;
  const h = 1100;
  const dust = [];
  const glow = [];

  for (let i = 0; i < 140; i++) {
    const x = (rnd(i + 1) * w).toFixed(1);
    const y = (rnd(i + 40) * h).toFixed(1);
    const t = rnd(i + 80);
    const alpha = (0.22 + t * 0.7).toFixed(2);
    const spread = t > 0.82 ? 1.1 : t > 0.55 ? 0.4 : 0;
    dust.push(`${x}px ${y}px 0 ${spread}px rgba(255,255,255,${alpha})`);
  }

  for (let i = 0; i < 18; i++) {
    const x = (rnd(i + 200) * w).toFixed(1);
    const y = (rnd(i + 260) * h).toFixed(1);
    glow.push(`${x}px ${y}px 6px 0 rgba(255,255,255,0.35)`);
  }

  const dustEl = document.createElement("i");
  dustEl.className = "starfield__dust";
  dustEl.style.boxShadow = dust.join(",");

  const glowEl = document.createElement("i");
  glowEl.className = "starfield__glow";
  glowEl.style.boxShadow = glow.join(",");

  root.append(dustEl, glowEl);

  for (let i = 0; i < 8; i++) {
    const spark = document.createElement("i");
    spark.className = "starfield__spark";
    spark.style.left = `${(rnd(i + 400) * 100).toFixed(2)}%`;
    spark.style.top = `${(rnd(i + 420) * 100).toFixed(2)}%`;
    spark.style.animationDelay = `${(i * 0.4).toFixed(1)}s`;
    root.appendChild(spark);
  }
}

document.querySelectorAll(".starfield").forEach(paintStarfield);
