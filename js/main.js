const programCards = document.getElementById("programCards");
const timetableBoard = document.getElementById("timetableBoard");
const toastEl = document.getElementById("toast");

function renderPrograms(key) {
  programCards.innerHTML = programs[key]
    .map(
      (item) => `
      <article class="p-card">
        <img src="${item.img}" alt="${item.title}">
        <div class="p-card__body">
          <h3>${item.title}</h3>
          <p>${item.desc}</p>
          <div class="p-card__meta">
            <span><img src="./img/location.png" alt=""> ${item.place}</span>
            <span><img src="./img/date.png" alt=""> ${item.time}</span>
          </div>
        </div>
      </article>`
    )
    .join("");
}

function renderTimetable(key) {
  const data = timetable[key];
  timetableBoard.innerHTML = `
    <p class="tt-title">${data.label}</p>
    ${data.rows
      .map(
        (row, i) => `
      <div class="tt-row${i === 0 ? " is-first" : ""}">
        <div class="tt-time">${row[0]}</div>
        <div class="tt-rail"><span class="tt-dot"></span></div>
        <div class="tt-name">${row[1]}</div>
        <div class="tt-place"><img src="./img/location.png" alt=""> ${row[2]}</div>
        <div class="tt-tag">${row[3]}</div>
      </div>`
      )
      .join("")}
  `;
}

